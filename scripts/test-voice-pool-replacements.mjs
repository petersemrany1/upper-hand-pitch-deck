import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const {PGlite}=await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db=new PGlite();
const token='00000000-0000-4000-8000-000000000001', other='00000000-0000-4000-8000-000000000002';
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
GRANT USAGE ON SCHEMA public TO authenticated,service_role;
CREATE FUNCTION is_admin_user() RETURNS boolean LANGUAGE sql STABLE AS $$SELECT current_setting('test.admin',true)='yes'$$;
CREATE FUNCTION has_sales_role(text[]) RETURNS boolean LANGUAGE sql STABLE AS $$SELECT current_setting('test.admin',true)='yes'$$;
CREATE TABLE phone_numbers(number text PRIMARY KEY,twilio_sid text,friendly_name text,status text,mms_enabled boolean);
INSERT INTO phone_numbers SELECT '+6140000000'||g,NULL,NULL,CASE WHEN g=7 THEN 'retired' ELSE 'active' END,false FROM generate_series(1,7) g;`);
const sql=readFileSync(new URL('../supabase/migrations/20261120010000_voice_pool_replacements.sql',import.meta.url),'utf8').split('-- Scheduler dispatch')[0];
await db.exec(sql);
const q=async(sql,args=[])=>(await db.query(sql,args)).rows[0]?.r;
const lease=t=>q('SELECT voice_pool_lease($1) r',[t]);
const reserve=(phone,cents=825,currency='usd',t=token)=>q('SELECT voice_pool_reserve($1,$2,$3,$4) r',[t,phone,cents,currency]);
const begin=id=>q('SELECT voice_pool_begin($1,$2) r',[token,id]);
const finish=(id,sid)=>q('SELECT voice_pool_finish($1,$2,false) r',[id,sid]);
const ticket='a'.repeat(64);
const job=(await db.query("INSERT INTO voice_pool_jobs(token_hash,dry_run,expires_at) VALUES(encode(sha256(convert_to($1,'UTF8')),'hex'),true,now()+interval '2 minutes') RETURNING id",[ticket])).rows[0].id;
const consume=(id,t,dry)=>q('SELECT consume_voice_pool_job($1,$2,$3) r',[id,t,dry]);
assert.equal(await consume(job,'b'.repeat(64),true),false,'wrong ticket denied');
assert.equal(await consume(job,ticket,false),false,'dry-run ticket cannot authorize a purchase');
assert.equal(await consume(job,ticket,true),true); assert.equal(await consume(job,ticket,true),false,'job replay denied');
await db.exec("UPDATE voice_pool_jobs SET consumed_at=NULL,expires_at=now()-interval '1 second'");
assert.equal(await consume(job,ticket,true),false,'expired ticket denied');
assert.equal(await lease(token),null,'disabled until approval');
await db.exec("UPDATE voice_pool_settings SET enabled=true,approved_at=now(),baseline_numbers=ARRAY(SELECT number FROM phone_numbers)");
assert.ok(await lease(token)); assert.equal(await lease(other),null,'concurrent worker excluded');
for(const [amount,currency] of [[826,'usd'],[825,'aud'],[0,'usd']]) await assert.rejects(reserve('+61485000001',amount,currency),/budget/);
await assert.rejects(reserve('+61485000001',825,'usd',other),/lease/);
const one=await reserve('+61485000001'); assert.ok(one.id);
await assert.rejects(reserve('+61485000002'),/reconciliation/);
await db.exec("UPDATE voice_pool_settings SET lease_until=now()-interval '1 second'");
assert.ok(await lease(other)); assert.equal(await begin(one.id),false,'expired worker cannot begin a purchase');
await q('SELECT voice_pool_lease($1,true) r',[other]); assert.ok(await lease(token));
assert.equal(await begin(one.id),true); assert.equal(await begin(one.id),false,'only one external request may begin');
await db.query("UPDATE voice_pool_purchases SET state='uncertain' WHERE id=$1",[one.id]);
await assert.rejects(reserve('+61485000002'),/reconciliation/);
await finish(one.id,'PN'+'1'.repeat(32)); await finish(one.id,'PN'+'1'.repeat(32));
assert.equal(await reserve('+61485000002'),null,'target restored, no extra purchase');
await db.exec("UPDATE phone_numbers SET status='retired' WHERE number='+61485000001'");
await finish(one.id,'PN'+'1'.repeat(32));
assert.equal((await db.query("SELECT status FROM phone_numbers WHERE number='+61485000001'")).rows[0].status,'retired','reconciliation cannot reactivate retired caller ID');
const two=await reserve('+61485000002'); await begin(two.id); await finish(two.id,'PN'+'2'.repeat(32));
assert.deepEqual(await q('SELECT voice_pool_budget() r'),{used_numbers:2,committed_cents:1650});
await db.exec("UPDATE phone_numbers SET status='retired' WHERE number='+61485000002'");
await assert.rejects(reserve('+61485000003'),/budget/,'retiring replacements does not reset allowance');
await db.exec("DELETE FROM phone_numbers WHERE number='+61485000002'");
assert.deepEqual(await q('SELECT voice_pool_budget() r'),{used_numbers:2,committed_cents:1650},'lost rows cannot hide already committed purchases');
await db.exec("TRUNCATE voice_pool_purchases; DELETE FROM phone_numbers WHERE number='+61485000001'");
const rejected=await reserve('+61485000004'); await begin(rejected.id);
await db.exec("UPDATE voice_pool_purchases SET state='failed'");
assert.deepEqual(await q('SELECT voice_pool_budget() r'),{used_numbers:0,committed_cents:0});
const retry=await reserve('+61485000004'); assert.equal(retry.id,rejected.id,'definite rejection can safely retry same available candidate');
await db.exec("UPDATE voice_pool_purchases SET state='failed'; INSERT INTO phone_numbers VALUES('+61485000005',NULL,NULL,'retired',false)");
assert.deepEqual(await q('SELECT voice_pool_budget() r'),{used_numbers:1,committed_cents:825},'manual additions count against cap too');
await db.exec("SET ROLE authenticated");
await assert.rejects(lease(token),/permission denied/); await assert.rejects(db.query('SELECT * FROM voice_pool_settings'),/permission denied/);
await assert.rejects(consume(job,ticket,true),/permission denied/); await assert.rejects(db.query('SELECT * FROM voice_pool_jobs'),/permission denied/);
await assert.rejects(q('SELECT voice_pool_status() r'),/Administrator/);
await db.exec("SELECT set_config('test.admin','yes',false)"); assert.equal((await q('SELECT voice_pool_status() r')).max_monthly_cents,1650);
await db.exec('RESET ROLE; SET ROLE anon'); await assert.rejects(q('SELECT voice_pool_status() r'),/permission denied/);
await db.close();
console.log('PASS: approval gate, lease exclusion, price/currency limits, intent dedupe, reconciliation, target, lifetime budget, manual additions, admin isolation.');
