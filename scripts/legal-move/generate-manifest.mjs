// Writes src/legal/move/manifest.ts: the Legal tables in a safe copy order
// (parents before children), each with its key, the columns the database
// fills itself, and the self/cyclic links that must be filled in a second pass.
//   node scripts/legal-move/generate-manifest.mjs .legal-move/schema.json
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { withoutHelpers } from "./generate-schema.mjs";

const schema = withoutHelpers(JSON.parse(readFileSync(process.argv[2] ?? ".legal-move/schema.json", "utf8")));
const tables = new Map(schema.tables.map((t) => [t.name, t]));
const fks = schema.constraints
  .filter((c) => c.type === "f" && !/REFERENCES auth\./.test(c.def))
  .map((c) => {
    const m = /FOREIGN KEY \(([^)]+)\) REFERENCES (?:public\.)?("?)([a-z_0-9]+)\2/.exec(c.def);
    return { table: c.table.replace(/^public\./, ""), cols: m[1].split(",").map((s) => s.trim().replace(/"/g, "")), ref: m[3] };
  });

// Order parents first; links that point at the same table, or close a cycle, are deferred.
const deferred = new Map();
const deps = new Map([...tables.keys()].map((t) => [t, new Set()]));
for (const f of fks) {
  if (f.ref === f.table) {
    deferred.set(f.table, [...(deferred.get(f.table) ?? []), ...f.cols]);
    continue;
  }
  deps.get(f.table)?.add(f.ref);
}
// Break cycles first (deferring a link whose columns may be empty), then sort.
const nullable = (f) => f.cols.every((c) => !tables.get(f.table).columns.find((x) => x.name === c)?.not_null);
function findCycle() {
  const state = new Map();
  let found = null;
  function dfs(t, stack) {
    if (found || state.get(t) === 2) return;
    if (state.get(t) === 1) {
      found = [...stack.slice(stack.indexOf(t)), t];
      return;
    }
    state.set(t, 1);
    for (const d of deps.get(t)) if (tables.has(d)) dfs(d, [...stack, t]);
    state.set(t, 2);
  }
  for (const t of [...tables.keys()].sort()) dfs(t, []);
  return found;
}
for (let cycle = findCycle(); cycle; cycle = findCycle()) {
  const links = cycle.slice(0, -1).map((from, i) => fks.find((x) => x.table === from && x.ref === cycle[i + 1]));
  const f = links.find(nullable);
  if (!f) throw new Error(`No nullable link to break cycle ${cycle.join(" > ")}`);
  deferred.set(f.table, [...(deferred.get(f.table) ?? []), ...f.cols]);
  deps.get(f.table).delete(f.ref);
}
const order = [];
const done = new Set();
function visit(t) {
  if (done.has(t)) return;
  done.add(t);
  for (const d of deps.get(t)) if (tables.has(d)) visit(d);
  order.push(t);
}
for (const t of [...tables.keys()].sort()) visit(t);

const pk = new Map();
for (const c of schema.constraints.filter((c) => c.type === "p")) {
  pk.set(c.table.replace(/^public\./, ""), /PRIMARY KEY \(([^)]+)\)/.exec(c.def)[1].split(",").map((s) => s.trim().replace(/"/g, "")));
}

const entries = order.map((name) => {
  const t = tables.get(name);
  return {
    name,
    key: pk.get(name) ?? [],
    skip: t.columns.filter((c) => c.identity === "a" || c.generated === "s").map((c) => c.name),
    deferred: [...new Set(deferred.get(name) ?? [])],
    rows: schema.row_counts[name] ?? 0,
  };
});

mkdirSync("src/legal/move", { recursive: true });
mkdirSync("src/legal/runtime", { recursive: true });
writeFileSync(
  "src/legal/move/manifest.ts",
  `// Generated by scripts/legal-move/generate-manifest.mjs from the Legal schema export. Do not edit.
// Legal tables in copy order (parents first). "deferred" links are filled in a
// second pass because they point at the same table or close a cycle.
export type LegalTable = { name: string; key: string[]; skip: string[]; deferred: string[]; rows: number };

export const LEGAL_TABLES: LegalTable[] = ${JSON.stringify(entries, null, 2)};

export const LEGAL_TABLE_NAMES: ReadonlySet<string> = new Set(LEGAL_TABLES.map((t) => t.name));
`,
);
console.log(`${entries.length} tables; deferred:`, entries.filter((e) => e.deferred.length).map((e) => `${e.name}(${e.deferred})`).join(" "), "; no key:", entries.filter((e) => !e.key.length).map((e) => e.name));

// Names the runtime translator (src/legal/runtime/prefix.ts) maps to legal_ / legal-.
const fkNames = schema.constraints.filter((c) => c.type === "f" && !/REFERENCES auth\./.test(c.def)).map((c) => c.name);
writeFileSync(
  "src/legal/runtime/names.ts",
  `// Generated by scripts/legal-move/generate-manifest.mjs from the Legal schema export. Do not edit.
// Legal database names that live under a legal_ prefix (buckets legal-) in the portal database.
export const LEGAL_RELATIONS: ReadonlySet<string> = new Set(${JSON.stringify([...schema.tables.map((t) => t.name), ...schema.views.map((v) => v.name)].sort())});
export const LEGAL_FUNCTIONS: ReadonlySet<string> = new Set(${JSON.stringify([...new Set(schema.functions.map((f) => f.name))].sort())});
export const LEGAL_BUCKETS: ReadonlySet<string> = new Set(${JSON.stringify(schema.buckets.map((b) => b.id).sort())});
export const LEGAL_FOREIGN_KEYS: ReadonlySet<string> = new Set(${JSON.stringify(fkNames.sort())});
`,
);
